export function startOfDay(date: Date): Date {
  const d = new Date(date);
  d.setHours(0, 0, 0, 0);
  return d;
}

export function endOfDay(date: Date): Date {
  const d = new Date(date);
  d.setHours(23, 59, 59, 999);
  return d;
}

export function startOfMonth(date: Date): Date {
  return new Date(date.getFullYear(), date.getMonth(), 1, 0, 0, 0, 0);
}

export function endOfMonth(date: Date): Date {
  return new Date(date.getFullYear(), date.getMonth() + 1, 0, 23, 59, 59, 999);
}

// "YYYY-MM-DD" sozinho é interpretado como meia-noite UTC; forçamos o horário local
export function parseLocalDate(value: string): Date {
  return /^\d{4}-\d{2}-\d{2}$/.test(value) ? new Date(`${value}T00:00:00`) : new Date(value);
}

export function parseDateRange(from?: string, to?: string): { from?: Date; to?: Date } {
  return {
    from: from ? startOfDay(parseLocalDate(from)) : undefined,
    to: to ? endOfDay(parseLocalDate(to)) : undefined,
  };
}

// "YYYY-MM-DD" no fuso do servidor (Brasil); toISOString() usaria UTC
export function toDateKey(date: Date): string {
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;
}
